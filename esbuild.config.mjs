import { builtinModules } from 'node:module';
import process from 'node:process';
import esbuild from 'esbuild';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// pi-ai's provider-env keeps a `require("node:fs")` for Bun sandboxes. Obsidian Mobile has no
// Node, so that module is swapped for a stub that only reads the explicit overrides.
const providerEnvStub = {
	name: 'pi-ai-provider-env-stub',
	setup(build) {
		build.onResolve({ filter: /[\\/]utils[\\/]provider-env(\.js)?$/ }, (args) => ({
			path: args.path,
			namespace: 'provider-env-stub',
		}));
		build.onLoad({ filter: /.*/, namespace: 'provider-env-stub' }, () => ({
			contents:
				'export function getProviderEnvValue(name, env) { return env?.[name] || undefined; }',
			loader: 'js',
		}));
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	platform: 'browser',
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	plugins: [providerEnvStub],
	define: { 'process.env.NODE_ENV': prod ? '"production"' : '"development"' },
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
